  @override
  Future<List<NovelBook>> getPopularNovels({int page = 1}) async {
    final custom = await _loadCustomNovels();
    return [..._curatedNovels, ...custom];
  }

  @override
  Future<List<NovelBook>> searchNovels(String query, {int page = 1}) async {
    final all = await getPopularNovels();
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return all;
    return all.where((b) => b.title.toLowerCase().contains(q) || b.author.toLowerCase().contains(q)).toList();
  }

  @override
  Future<List<NovelChapter>> getChapters(String novelId, {String? novelUrl}) async {
    final all = await getPopularNovels();
    try {
      final book = all.firstWhere((b) => b.id == novelId);
      return book.chapters;
    } catch (_) {
      return [];
    }
  }

  @override
  Future<String> getChapterContent(NovelChapter chapter) async {
    return chapter.content;
  }

  Future<List<NovelBook>> _loadCustomNovels() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final list = prefs.getStringList('custom_library_novels') ?? [];
      final List<NovelBook> result = [];

      for (final raw in list) {
        final data = jsonDecode(raw);
        final chaps = (data['chapters'] as List).map((c) => NovelChapter(
          id: c['id'],
          title: c['title'],
          chapterNumber: c['number'] ?? '1',
          content: c['content'],
          publishedAt: DateTime.now(),
        )).toList();

        result.add(NovelBook(
          id: data['id'],
          title: data['title'],
          author: data['author'],
          coverUrl: data['coverUrl'] ?? '',
          description: data['description'] ?? '',
          chapters: chaps,
          isCustom: true,
          source: sourceName,
        ));
      }
      return result;
    } catch (e) {
      debugPrint('Error loading custom novels: $e');
      return [];
    }
  }
