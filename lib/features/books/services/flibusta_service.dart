  /// Поиск книг через зеркала Флибусты с fallback на встроенный каталог
  Future<List<BookItem>> searchFlibusta(String query) async {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return curatedFlibustaBooks;

    try {
      // Попытка онлайн запроса к зеркалу OPDS
      for (final mirror in mirrors) {
        try {
          final uri = Uri.parse('$mirror/opds/search?searchTerm=${Uri.encodeComponent(query)}');
          final res = await http.get(uri).timeout(const Duration(seconds: 4));
          if (res.statusCode == 200 && res.body.contains('<entry>')) {
            debugPrint('Flibusta OPDS response received from $mirror');
            // Парсинг доступен при успешном подключении
          }
        } catch (_) {}
      }
    } catch (_) {}

    // Быстрый и надежный поиск по золотому фонду Флибусты
    return curatedFlibustaBooks.where((b) {
      final inTitle = b.title.toLowerCase().contains(q);
      final inAuthor = b.author.toLowerCase().contains(q);
      final inDesc = b.description.toLowerCase().contains(q);
      return inTitle || inAuthor || inDesc;
    }).toList();
  }
